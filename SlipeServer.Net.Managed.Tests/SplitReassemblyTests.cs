    /// <summary>The four parts in capture order.</summary>
    internal static readonly string[] RecordedSplitParts =
    {
        SplitPart0,
        SplitPart1,
        SplitPart2,
        SplitPart3,
    };

    // ---- expectations, all derived from the capture bytes rather than from the port ----

    /// <summary>9104 + 9104 + 9104 + 5648 bits, each part byte-aligned: 4120 bytes.</summary>
    private const int ReassembledPayloadBytes = 4120;

    /// <summary>The delivered view drops the leading wire id: 4119 bytes.</summary>
    private const int DeliveredDataBytes = 4119;

    /// <summary>The first 16 bytes after the wire id, read straight out of record 284.</summary>
    private const string DataHead = "841B5D185B995D141C9BD89954DC1B1A";

    /// <summary>The last 16 bytes of the message, read straight out of record 295.</summary>
    private const string DataTail = "0123456789abcdef";

    /// <summary>Offset of the 4096-byte event argument inside the delivered view.</summary>
    private const int ArgumentOffset = 23;

    /// <summary>The event argument the client sent: "0123456789abcdef" repeated 256 times.</summary>
    private const int ArgumentBytes = 4096;

    [Fact]
    public void RecordedClientSplitMessageIsReassembledIntoOneLuaEvent()
    {
        using var harness = new WrapperHarness();
        harness.ConnectSession();

        foreach (string part in RecordedSplitParts)
            harness.InjectHex(part);

        Received delivered = Assert.Single(harness.Received, IsTheReassembledEvent);

        byte[] data = delivered.Data;
        Assert.Equal(DeliveredDataBytes, data.Length);
        Assert.Equal(WireTestKit.Hex(DataHead), data[..16]);
        Assert.Equal(DataTail, Encoding.ASCII.GetString(data, data.Length - 16, 16));
        Assert.Equal(
            string.Concat(Enumerable.Repeat(DataTail, ArgumentBytes / 16)),
            Encoding.ASCII.GetString(data, ArgumentOffset, ArgumentBytes));

        Assert.Contains(harness.Trace, line => line.StartsWith("reassembled sid=0 from 4 part(s)", StringComparison.Ordinal));
        Assert.DoesNotContain(harness.Trace, line => line.StartsWith("buffered split part 3/4", StringComparison.Ordinal));
    }

    [Fact]
    public void RecordedClientSplitPartsArrivingOutOfOrderReassembleIdentically()
    {
        using var harness = new WrapperHarness();
        harness.ConnectSession();

        // Part 3 last in capture order; first here. RakNet does not promise part order, and the
        // datagram that carries it also carries nine unrelated packets, so those are injected before
        // the message can complete.
        harness.InjectHex(SplitPart3);
        harness.InjectHex(SplitPart2);
        harness.InjectHex(SplitPart1);
        Assert.DoesNotContain(harness.Received, IsTheReassembledEvent);

        harness.InjectHex(SplitPart0);

        Received delivered = Assert.Single(harness.Received, IsTheReassembledEvent);
        Assert.Equal(WireTestKit.Hex(DataHead), delivered.Data[..16]);
        Assert.Equal(
            string.Concat(Enumerable.Repeat(DataTail, ArgumentBytes / 16)),
            Encoding.ASCII.GetString(delivered.Data, ArgumentOffset, ArgumentBytes));
    }

    [Fact]
    public void RecordedClientSplitMessageIsNotDeliveredWhileAPartIsMissing()
    {
        using var harness = new WrapperHarness();
        harness.ConnectSession();

        harness.InjectHex(SplitPart0);
        harness.InjectHex(SplitPart1);
        harness.InjectHex(SplitPart2);

        Assert.Empty(harness.Received);
        Assert.DoesNotContain(harness.Trace, line => line.StartsWith("reassembled ", StringComparison.Ordinal));
    }

    [Fact]
    public void RecordedClientSplitMessageRetransmittedIsDeliveredOnce()
    {
        using var harness = new WrapperHarness();
        harness.ConnectSession();

        foreach (string part in RecordedSplitParts)
            harness.InjectHex(part);

        // A peer that missed the ack resends the whole message with the same sequence numbers.
        foreach (string part in RecordedSplitParts)
            harness.InjectHex(part);

        Assert.Single(harness.Received, IsTheReassembledEvent);
    }

    [Fact]
    public void RecordedClientSplitPartsAreAcknowledgedWhileTheMessageIsIncomplete()
    {
        using var harness = new WrapperHarness();
        harness.ConnectSession();

        harness.InjectHex(SplitPart0);
        harness.InjectHex(SplitPart1);

        // Each part carries its own sequence number, so the reliability layer acks each one even
        // though the logical message is still incomplete. A peer whose part went unacked would
        // re-send it forever.
        Assert.Contains(harness.Tx, line => line.Classification.Contains("acks=1 ", StringComparison.Ordinal));
        Assert.Empty(harness.Received);
    }

    /// <summary>
    /// The one delivery that can only be the reassembled message: no recorded part and none of the
    /// nine packets sharing part 3's datagram is this large.
    /// </summary>
    private static bool IsTheReassembledEvent(Received received) =>
        received.Id == PacketId.PACKET_ID_LUA_EVENT && received.Data.Length == DeliveredDataBytes;
}
